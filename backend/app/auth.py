"""Temporary single-user authentication for hosted demonstrations."""

from __future__ import annotations

import base64
import hashlib
import hmac
import secrets
import threading
import time
from collections import defaultdict, deque
from dataclasses import dataclass
from typing import Deque
from urllib.parse import urlsplit

from fastapi import Request
from fastapi.responses import JSONResponse
from starlette.types import ASGIApp, Receive, Scope, Send

from app.services.identity import reset_current_actor, set_current_actor

SESSION_COOKIE = "__Host-threatlens_session"
CSRF_HEADER = "x-csrf-token"
PUBLIC_PATHS = {"/api/health", "/api/auth/login", "/api/auth/session", "/api/auth/logout"}
COLLECTOR_PATHS = {
    "/api/ingestion/windows/agent.ps1",
    "/api/ingestion/windows/events",
    "/api/ingestion/windows/heartbeat",
}


def _b64decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def validate_password_hash(encoded: str) -> None:
    try:
        algorithm, n, r, p, salt, digest = encoded.split("$")
        if algorithm != "scrypt" or (int(n), int(r), int(p)) != (16384, 8, 1):
            raise ValueError
        if len(_b64decode(salt)) < 16 or len(_b64decode(digest)) != 32:
            raise ValueError
    except (ValueError, TypeError) as exc:
        raise RuntimeError("THREATLENS_DEMO_PASSWORD_HASH must be a valid scrypt hash generated by the provided script.") from exc


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=16384, r=8, p=1, dklen=32)
    encode = lambda value: base64.urlsafe_b64encode(value).decode("ascii").rstrip("=")
    return f"scrypt$16384$8$1${encode(salt)}${encode(digest)}"


def verify_password(password: str, encoded: str) -> bool:
    validate_password_hash(encoded)
    _, _, _, _, salt, expected = encoded.split("$")
    actual_digest = hashlib.scrypt(password.encode("utf-8"), salt=_b64decode(salt), n=16384, r=8, p=1, dklen=32)
    return hmac.compare_digest(actual_digest, _b64decode(expected))


@dataclass(frozen=True)
class Session:
    username: str
    csrf_token: str
    expires_at: float


class DemoAuth:
    """In-memory server-side sessions and login throttling for one demo process."""

    def __init__(self, settings, clock=time.monotonic):
        self.username = settings.demo_username.strip()
        self.password_hash = settings.demo_password_hash
        self.ttl = settings.demo_session_ttl_seconds
        self.secure_cookie = settings.session_cookie_secure
        self.same_site = settings.cookie_samesite
        self.allowed_origins = frozenset(settings.allowed_origins)
        self.max_attempts = settings.demo_login_attempts
        self.window = settings.demo_login_window_seconds
        self.global_max_attempts = settings.demo_global_login_attempts
        self.clock = clock
        self._sessions: dict[str, Session] = {}
        self._attempts: dict[str, Deque[float]] = defaultdict(deque)
        self._global_attempts: Deque[float] = deque()
        self._lock = threading.Lock()
        if not self.username or len(self.username) > 128:
            raise RuntimeError("THREATLENS_DEMO_USERNAME must contain 1–128 characters in demo mode.")
        origins = [urlsplit(origin) for origin in self.allowed_origins]
        if not origins or any(
            origin.scheme != "https" or not origin.netloc or origin.path or origin.query or origin.fragment
            for origin in origins
        ):
            raise RuntimeError("THREATLENS_CORS_ORIGINS must contain exact HTTPS origins in demo mode.")
        validate_password_hash(self.password_hash)
        if self.same_site == "none" and not self.secure_cookie:
            raise RuntimeError("SameSite=None requires secure session cookies.")

    def origin_allowed(self, origin: str | None) -> bool:
        return origin is not None and origin in self.allowed_origins

    def _prune(self, values: Deque[float], now: float) -> None:
        while values and now - values[0] >= self.window:
            values.popleft()

    def allow_login_attempt(self, peer: str) -> bool:
        now = self.clock()
        with self._lock:
            self._prune(self._attempts[peer], now)
            self._prune(self._global_attempts, now)
            if len(self._attempts[peer]) >= self.max_attempts or len(self._global_attempts) >= self.global_max_attempts:
                return False
            self._attempts[peer].append(now)
            self._global_attempts.append(now)
            return True

    def create_session(self) -> tuple[str, Session]:
        now = self.clock()
        token = secrets.token_urlsafe(32)
        session = Session(self.username, secrets.token_urlsafe(32), now + self.ttl)
        with self._lock:
            for expired_token in [key for key, value in self._sessions.items() if value.expires_at <= now]:
                self._sessions.pop(expired_token, None)
            if len(self._sessions) >= 1000:
                oldest = min(self._sessions, key=lambda key: self._sessions[key].expires_at)
                self._sessions.pop(oldest, None)
            self._sessions[token] = session
        return token, session

    def get_session(self, token: str | None) -> Session | None:
        if not token:
            return None
        now = self.clock()
        with self._lock:
            session = self._sessions.get(token)
            if session is None:
                return None
            if session.expires_at <= now:
                self._sessions.pop(token, None)
                return None
            return session

    def invalidate(self, token: str | None) -> None:
        if token:
            with self._lock:
                self._sessions.pop(token, None)

    def csrf_valid(self, session: Session, supplied: str | None) -> bool:
        return bool(supplied) and hmac.compare_digest(session.csrf_token, supplied)

    def set_cookie(self, response, token: str, max_age: int | None = None) -> None:
        response.set_cookie(
            SESSION_COOKIE,
            token,
            max_age=max_age if max_age is not None else self.ttl,
            httponly=True,
            secure=self.secure_cookie,
            samesite=self.same_site,
            path="/",
        )

    def clear_cookie(self, response) -> None:
        response.delete_cookie(SESSION_COOKIE, path="/", secure=self.secure_cookie, httponly=True, samesite=self.same_site)


class DemoAuthMiddleware:
    """Enforce server sessions and CSRF checks on all dashboard API routes."""

    def __init__(self, app: ASGIApp):
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        app_state = scope["app"].state
        state = scope.setdefault("state", {})
        if app_state.auth_mode != "demo":
            await self.app(scope, receive, send)
            return

        request = Request(scope, receive=receive)
        path = request.url.path
        method = request.method.upper()
        if not path.startswith("/api/") or method == "OPTIONS" or path in PUBLIC_PATHS or path in COLLECTOR_PATHS:
            await self.app(scope, receive, send)
            return

        auth: DemoAuth = app_state.demo_auth
        session_token = request.cookies.get(SESSION_COOKIE)
        session = auth.get_session(session_token)
        if session is None:
            response = JSONResponse({"detail": "Authentication required."}, status_code=401)
            if session_token:
                auth.clear_cookie(response)
            await response(scope, receive, send)
            return

        if method not in {"GET", "HEAD"}:
            if not auth.origin_allowed(request.headers.get("origin")):
                await JSONResponse({"detail": "Request origin is not allowed."}, status_code=403)(scope, receive, send)
                return
            if not auth.csrf_valid(session, request.headers.get(CSRF_HEADER)):
                await JSONResponse({"detail": "CSRF validation failed."}, status_code=403)(scope, receive, send)
                return

        if _is_demo_restricted_action(path, method):
            await JSONResponse({"detail": "This administrative action is unavailable in demo access."}, status_code=403)(scope, receive, send)
            return

        state["demo_username"] = session.username
        actor_context = set_current_actor("Demo analyst")
        try:
            await self.app(scope, receive, send)
        finally:
            reset_current_actor(actor_context)


def _is_demo_restricted_action(path: str, method: str) -> bool:
    if path.startswith("/api/ingestion/sources"):
        return True
    if path == "/api/settings/detection" and method != "GET":
        return True
    if path.startswith(("/api/detection/rules", "/api/detection/exceptions")) and method not in {"GET", "HEAD"}:
        return not path.endswith("/preview")
    if path.startswith("/api/intelligence/feeds") and method != "GET":
        return True
    return False
